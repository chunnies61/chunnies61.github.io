// Builds src/components/metricIcons.generated.js: the filled (solid) Iconstica icons used in the
// small colour chips on the case-study metric cards.
//
//   node scripts/build-metric-icons.mjs
//   ICONSTICA_DIR=/path/to/iconstica_.../svg node scripts/build-metric-icons.mjs
//
// A metric picks its icon with `"icon": "<name>"` in the case-study JSON, where <name> is the
// pack's file name without .svg. To use another icon, add its name to ICONS below and re-run.
import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const srcDir =
  process.env.ICONSTICA_DIR ||
  "/Users/yichunliu/Downloads/iconstica_v1.2.0-premium_package/svg";
const out = join(here, "../src/components/metricIcons.generated.js");

const ICONS = [
  "bar-chart-analysis",
  "check-circle",
  "clock",
  "exclamation-triangle",
  "face-smile",
  "headphone-mic",
  "heartbeat",
  "pen-to-square",
  "bolt",
  "hourglass",
  "user-circle",
];

const ATTRS = {
  d: "d",
  fill: "fill",
  "fill-rule": "fillRule",
  "clip-rule": "clipRule",
  opacity: "opacity",
  "fill-opacity": "fillOpacity",
};

const icons = {};
for (const name of ICONS) {
  const path = join(srcDir, "filled", `${name}.svg`);
  if (!existsSync(path)) throw new Error(`${name}: ${path} not found`);
  const svg = readFileSync(path, "utf8");
  const elements = [...svg.matchAll(/<(\w+)\s([^>]*?)\/?>/g)].filter(([, tag]) => tag !== "svg");
  if (!elements.length) throw new Error(`${name}: no shapes`);
  icons[name] = elements.map(([, tag, attrText]) => {
    if (tag !== "path") throw new Error(`${name}: <${tag}> — only <path> is supported`);
    const props = {};
    for (const [, key, value] of attrText.matchAll(/([\w-]+)="([^"]*)"/g)) {
      if (!(key in ATTRS)) throw new Error(`${name}: unsupported attribute ${key}`);
      props[ATTRS[key]] = /^#[0-9a-f]{3,8}$/i.test(value) ? "currentColor" : value;
    }
    return props;
  });
}

writeFileSync(
  out,
  `// Generated by scripts/build-metric-icons.mjs from Iconstica (filled). Do not edit by hand —
// change the ICONS list in the script and re-run it.
export const METRIC_ICONS = {
${Object.entries(icons).map(([n, parts]) => `  ${JSON.stringify(n)}: ${JSON.stringify(parts)},`).join("\n")}
};
`
);
console.log(`wrote ${Object.keys(icons).length} filled icons → src/components/metricIcons.generated.js`);
