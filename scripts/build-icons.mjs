// Builds src/components/lra/icons.generated.js from the Iconstica icon pack.
//
// Only the icons the site uses are read (the MAP below), so the 13,000-file
// pack never enters the repo. Colours become `currentColor`, so an icon takes
// the text colour of whatever it sits in.
//
//   node scripts/build-icons.mjs                    # line style (default)
//   node scripts/build-icons.mjs --style filled     # any of: line filled duotone duoline broken mono
//   ICONSTICA_DIR=/path/to/iconstica_.../svg node scripts/build-icons.mjs
//
// To add an icon, add `ourName: "pack-file-name"` below and re-run.
import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const args = process.argv.slice(2);
const style = args.includes("--style") ? args[args.indexOf("--style") + 1] : "line";
const srcDir =
  process.env.ICONSTICA_DIR ||
  "/Users/yichunliu/Downloads/iconstica_v1.2.0-premium_package/svg";
const out = join(here, "../src/components/lra/icons.generated.js");

// our icon name → the pack's file name (without .svg)
const MAP = {
  add: "plus",
  apps: "grid",
  arrowBack: "arrow-left",
  arrowDown: "arrow-down",
  arrowForward: "arrow-right",
  arrowUp: "arrow-up",
  bank: "building-columns",
  bell: "bell",
  calendar: "calendar",
  check: "check",
  checkCircle: "check-circle",
  checklist: "list-ui",
  chevronRight: "chevron-right",
  close: "cancel",
  cloudOff: "cloud",
  coach: "graduation-cap",
  columns: "layout-3",
  delete: "trash",
  description: "file-lines",
  download: "download",
  error: "exclamation-circle",
  expand: "chevron-down",
  filter: "filter",
  help: "question-circle",
  home: "home",
  hourglass: "hourglass",
  info: "info-circle",
  lock: "lock",
  maximize: "square",
  minimize: "minus",
  moreHoriz: "3-dots-horizontal ", // the pack's file name has a trailing space
  moreVert: "3-dots-vertical",
  note: "pen-to-square",
  openInNew: "link-external",
  refresh: "arrow-rotate",
  search: "search",
  send: "send",
  sparkle: "sparkle",
  trendingUp: "arrow-trend-up",
  upload: "upload",
  warning: "exclamation-triangle",
};

const ATTRS = {
  d: "d",
  fill: "fill",
  stroke: "stroke",
  "stroke-width": "strokeWidth",
  "stroke-linecap": "strokeLinecap",
  "stroke-linejoin": "strokeLinejoin",
  "fill-rule": "fillRule",
  "clip-rule": "clipRule",
  opacity: "opacity",
  "fill-opacity": "fillOpacity",
  "stroke-opacity": "strokeOpacity",
};

const icons = {};
for (const [name, file] of Object.entries(MAP).sort(([a], [b]) => a.localeCompare(b))) {
  const path = join(srcDir, style, `${file}.svg`);
  if (!existsSync(path)) throw new Error(`${name}: ${path} not found`);
  const svg = readFileSync(path, "utf8");
  const elements = [...svg.matchAll(/<(\w+)\s([^>]*?)\/?>/g)].filter(([, tag]) => tag !== "svg");
  if (!elements.length) throw new Error(`${name}: no shapes in ${file}.svg`);
  icons[name] = elements.map(([, tag, attrText]) => {
    if (tag !== "path") throw new Error(`${name}: <${tag}> in ${file}.svg — only <path> is supported`);
    const props = {};
    for (const [, key, value] of attrText.matchAll(/([\w-]+)="([^"]*)"/g)) {
      if (!(key in ATTRS)) throw new Error(`${name}: unsupported attribute ${key} in ${file}.svg`);
      props[ATTRS[key]] = /^#[0-9a-f]{3,8}$/i.test(value) ? "currentColor" : value;
    }
    return props;
  });
}

const body = Object.entries(icons)
  .map(([name, parts]) => `  ${name}: ${JSON.stringify(parts)},`)
  .join("\n");
writeFileSync(
  out,
  `// Generated by scripts/build-icons.mjs from Iconstica (${style}). Do not edit by hand —
// change the MAP in the script and re-run it.
export const ICONS = {
${body}
};
`
);
console.log(`wrote ${Object.keys(icons).length} icons (${style}) → src/components/lra/icons.generated.js`);
